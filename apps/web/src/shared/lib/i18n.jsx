const DICTS = { ru: RU, en: EN, zh: ZH };

// Основная функция перевода. params — подстановки вида {name}.
export const t = (lang, key, params = {}) => {
    const dict = DICTS[lang] || RU;
    let str = dict[key] ?? RU[key] ?? key;
    Object.entries(params).forEach(([k, v]) => { str = str.replaceAll(`{${k}}`, v); });
    return str;
};
