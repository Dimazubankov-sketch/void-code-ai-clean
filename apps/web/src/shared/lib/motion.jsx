// ==========================================
// Motion tokens — единый источник кривых и длительностей
// ==========================================
// Раньше кривые и тайминги писались «на глаз» в каждом файле отдельно
// ('power2.out', 'back.out(2.4)', 0.09с, 0.4с — все разные). Теперь один
// набор токенов на всё приложение, чтобы движение ощущалось как одна
// система, а не как набор независимых эффектов.
//
// Кривые взяты не из головы: это те же строгие curve'ы, что используются
// в качественных продуктовых интерфейсах. Встроенные CSS/GSAP easing'и
// (ease-out, power2) для UI слишком слабые — им не хватает «щелчка».
//
// GSAP-строки эквивалентны cubic-bezier:
//   EASE.out     ≈ cubic-bezier(0.23, 1, 0.32, 1)     — вход/выход
//   EASE.inOut   ≈ cubic-bezier(0.77, 0, 0.175, 1)    — движение по экрану
//   EASE.drawer  ≈ cubic-bezier(0.32, 0.72, 0, 1)     — шторки/панели (iOS)
export const EASE = {
    // Сильный ease-out. Дефолт почти для всего: элемент стартует быстро,
    // поэтому интерфейс ощущается отзывчивым.
    out: 'cubic-bezier(0.23, 1, 0.32, 1)',
    // Для перемещения/морфинга уже видимого элемента.
    inOut: 'cubic-bezier(0.77, 0, 0.175, 1)',
    // Шторки, нижние панели, крупные поверхности.
    drawer: 'cubic-bezier(0.32, 0.72, 0, 1)',
    // Отпускание кнопки: едва заметный овершут, «живой» отклик.
    // Держим bounce низким — сильный отскок на обычной кнопке выглядит
    // дёшево, он уместен только для жестов с инерцией.
    press: 'back.out(1.7)',
};

// Длительности. UI-анимации держим под 300мс: 180мс дропдаун ощущается
// отзывчивее, чем 400мс.
export const DUR = {
    press: 0.1,      // нажатие кнопки — 100–160мс
    release: 0.22,   // возврат после отпускания
    tooltip: 0.16,   // тултипы, мелкие поповеры
    dropdown: 0.2,   // дропдауны, селекты
    panel: 0.32,     // модалки, панели
};

// Одна точка правды по reduced-motion. Уважать его обязательно: для
// вестибулярных расстройств движение — это не «стиль», а симптом.
// Важно: reduced motion ≠ ноль анимации. Оставляем opacity/цвет,
// убираем перемещения и масштабирование.
export function prefersReducedMotion() {
    return typeof window !== 'undefined'
        && typeof window.matchMedia === 'function'
        && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

// Готовый набор pointer-обработчиков для «дать кнопке отклик на нажатие»
// без переписывания её разметки: достаточно раскрыть результат в JSX
// ({...pressProps()}). Нужен там, где кнопка уже существует со своими
// классами и оборачивать её в PressButton было бы лишней перестройкой.
//
// Работает по pointerdown (не по click): отклик должен появляться в момент
// касания, иначе интерфейс ощущается запаздывающим.
export function pressProps(gsap, { scale = 0.94 } = {}) {
    if (prefersReducedMotion()) return {};
    const to = (el, s, duration, ease) => {
        if (el) gsap.to(el, { scale: s, duration, ease, overwrite: 'auto' });
    };
    return {
        onPointerDown: (e) => to(e.currentTarget, scale, DUR.press, EASE.out),
        onPointerUp: (e) => to(e.currentTarget, 1, DUR.release, EASE.press),
        onPointerLeave: (e) => to(e.currentTarget, 1, DUR.release, EASE.out),
    };
}
