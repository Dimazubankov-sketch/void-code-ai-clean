// ==========================================
// estimateRequestWeight — оценка «тяжести» запроса в токенах
// ==========================================
// Без изменений на бэкенде (LLM-провайдеры не возвращают точный usage на
// клиент через текущий /chats/:id/messages) — считаем ПРИБЛИЖЁННО по
// длине текста (~4 символа на токен, общепринятая грубая оценка для
// смеси русского/английского и кода) и доплатами за то, что реально
// увеличивает нагрузку и стоимость запроса у провайдера:
//   • вложенные картинки (vision) — на порядок дороже текста;
//   • уровень рассуждений — модель «думает» дольше и объёмнее;
//   • сама модель — Pro считается дороже Plus/Mini даже при равной длине
//     текста, т.к. запрос физически более ресурсоёмкий на бэкенде.
// Вызывается ПОСЛЕ получения ответа (используем реальную длину ответа, а
// не гадаем заранее) — поэтому чем длиннее/сложнее оказался ответ, тем
// больше реально спишется, а не фиксированная плата за сам факт отправки.
const REASONING_WEIGHT_MULTIPLIER = { low: 1, medium: 1.15, high: 1.4, max: 1.8 };
const MODEL_WEIGHT_MULTIPLIER = { flash: 0, flash_ext: 1, pro: 1.6 }; // flash = 0: безлимитна, вес не считаем
const IMAGE_ATTACHMENT_TOKENS = 700; // грубая оценка vision-токенов на одно вложенное фото

export const estimateRequestWeight = ({ inputText = '', responseText = '', imagesCount = 0, reasoningLevel = 'medium', modelId = 'flash_ext' }) => {
    const modelMultiplier = MODEL_WEIGHT_MULTIPLIER[modelId] ?? 1;
    if (modelMultiplier === 0) return 0; // Void Mini — не тратит лимит

    const charsToTokens = (s) => Math.ceil((s || '').length / 4);
    const inputTokens = charsToTokens(inputText);
    const outputTokens = charsToTokens(responseText);
    const imageTokens = Math.max(0, imagesCount) * IMAGE_ATTACHMENT_TOKENS;
    const reasoningMultiplier = REASONING_WEIGHT_MULTIPLIER[reasoningLevel] ?? REASONING_WEIGHT_MULTIPLIER.medium;

    const raw = (inputTokens + outputTokens + imageTokens) * reasoningMultiplier * modelMultiplier;
    // Минимум 10 токенов за любое платное сообщение — даже совсем
    // короткий запрос к Plus/Pro не должен списываться как «0».
    return Math.max(10, Math.round(raw));
};

